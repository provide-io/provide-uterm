    // ---- SessionLogger -------------------------------------------------

    private static object? FromNode(JsonNode? node) => node switch
    {
        null => null,
        JsonObject o => o.ToDictionary(kv => kv.Key, kv => FromNode(kv.Value)),
        JsonArray a => a.Select(FromNode).ToList(),
        JsonValue v when v.TryGetValue<string>(out var s) => s,
        JsonValue v when v.TryGetValue<bool>(out var b) => b,
        JsonValue v when v.TryGetValue<long>(out var l) => l,
        JsonValue v => v.GetValue<double>(),
        _ => throw new InvalidOperationException($"unexpected node {node.GetType()}"),
    };

    private static async Task<JsonArray> ReplayPayloadsAsync(JsonNode golden, Redactor? redactor)
    {
        var store = new InMemoryStore();
        var logger = new SessionLog(store, new SessionLogOpts
        {
            ControlChannelMode = ControlChannelMode.Wire,
            Redactor = redactor,
            FlushInterval = TimeSpan.FromHours(1),
        });
        await logger.StartAsync("s1");
        foreach (var call in golden["payloads"]!["calls"]!.AsArray())
        {
            var data = (Dictionary<string, object?>)FromNode(call!["data"])!;
            if ((string)call["method"]! == "event")
            {
                await logger.LogEventAsync((string)call["name"]!, data);
            }
            else
            {
                await logger.LogControlAsync((string)call["direction"]!, data);
            }
        }

        await logger.StopAsync();
        var entries = JsonNode.Parse(JsonSerializer.Serialize(await store.GetEntriesAsync("s1", new Query { Limit = 500 })))!.AsArray();
        foreach (var entry in entries)
        {
            var obj = entry!.AsObject();
            obj.Remove("ts");
            if ((string)obj["event"]! == "log_start")
            {
                obj["data"] = new JsonObject { ["stripped"] = true };
            }
        }

        return entries;
    }

    private static JsonNode LoadGolden() =>
        JsonNode.Parse(File.ReadAllText(TestData.PathTo("session_logger_golden.json")))!;

    [Fact]
    public async Task Payload_Parity_With_CPython_Redacted()
    {
        var golden = LoadGolden();
        var patterns = golden["payloads"]!["patterns"]!.AsArray().Select(p => (string)p!).ToList();
        var got = await ReplayPayloadsAsync(golden, R.MakeRedactor(patterns));
        Assert.True(JsonNode.DeepEquals(got, golden["payloads"]!["redacted"]), got.ToJsonString());
    }

    [Fact]
    public async Task Payload_Parity_With_CPython_Verbatim()
    {
        var golden = LoadGolden();
        var got = await ReplayPayloadsAsync(golden, null);
        Assert.True(JsonNode.DeepEquals(got, golden["payloads"]!["verbatim"]), got.ToJsonString());
    }

    [Fact]
    public async Task Payload_Is_Copied_Without_A_Redactor()
    {
        var store = new InMemoryStore();
        var logger = new SessionLog(store, new SessionLogOpts { ControlChannelMode = ControlChannelMode.Wire });
        await logger.StartAsync("s1");
        var data = new Dictionary<string, object?> { ["description"] = "S3cretValue", ["token"] = "abc" };
        await logger.LogEventAsync("annotation", data);
        data["description"] = "changed";
        await logger.StopAsync();
        var entry = (await store.GetEntriesAsync("s1", new Query { Limit = 500 })).Single(e => (string)e["event"]! == "annotation");
        Assert.Equal("{\"description\":\"S3cretValue\",\"token\":\"abc\"}", JsonSerializer.Serialize(entry["data"]));
    }

    [Fact]
    public async Task Control_Is_Dropped_In_Exclude_Mode_And_Nothing_Is_Redacted_Past_Quota()
    {
        var seen = new List<string>();
        Redactor counting = text =>
        {
            seen.Add(text);
            return text;
        };

        var store = new InMemoryStore();
        var excluded = new SessionLog(store, new SessionLogOpts { Redactor = counting });
        await excluded.StartAsync("s1");
        await excluded.LogControlAsync("send", new Dictionary<string, object?> { ["text"] = "x" });
        await excluded.StopAsync();
        Assert.Empty(seen);

        var full = new SessionLog(new InMemoryStore(), new SessionLogOpts { Redactor = counting, MaxBytes = 1, ControlChannelMode = ControlChannelMode.Wire });
        await full.StartAsync("s2");
        await full.LogEventAsync("dropped", new Dictionary<string, object?> { ["d"] = "dropped" });
        await full.LogControlAsync("send", new Dictionary<string, object?> { ["d"] = "dropped" });
        await full.LogAsync("read", new Dictionary<string, object?> { ["d"] = "dropped" });
        await full.StopAsync();
        Assert.Empty(seen);
    }

    [Fact]
    public async Task LogAsync_Redacts_Nested_And_Key_Sensitive_Values()
    {
        var store = new InMemoryStore();
        var logger = new SessionLog(store, new SessionLogOpts { Redactor = Secret });
        await logger.StartAsync("s1");
        await logger.LogAsync("custom", new Dictionary<string, object?>
        {
            ["nested"] = new Dictionary<string, object?> { ["x"] = "S3cretA" },
            ["password"] = "hunter2",
        });
        await logger.StopAsync();
        var entry = (await store.GetEntriesAsync("s1", new Query { Limit = 500 })).Single(e => (string)e["event"]! == "custom");
        Assert.Equal("{\"nested\":{\"x\":\"[REDACTED]\"},\"password\":\"[SECRET_REDACTED]\"}", JsonSerializer.Serialize(entry["data"]));
    }
}
