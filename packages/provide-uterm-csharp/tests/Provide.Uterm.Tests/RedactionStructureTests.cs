    private static readonly Redactor Secret = R.MakeRedactor([@"S3cret\w*"]);

    private static object? Nest(int depth, object? leaf, bool map)
    {
        var value = leaf;
        for (var i = 0; i < depth; i++)
        {
            value = map ? new Dictionary<string, object?> { ["k"] = value } : new List<object?> { value };
        }

        return value;
    }

    private static object? Innermost(object? value)
    {
        while (true)
        {
            switch (value)
            {
                case Dictionary<string, object?> d:
                    value = d["k"];
                    break;
                case List<object?> l:
                    value = l[0];
                    break;
                default:
                    return value;
            }
        }
    }

    [Fact]
    public void Constants_Match_The_Reference()
    {
        Assert.Equal(32, S.RedactMaxDepth);
        Assert.Equal("[NESTED_REDACTED]", S.DepthLimitMarker);
        Assert.Equal("[SECRET_REDACTED]", S.SensitiveKeyMarker);
        Assert.Equal(
            new[] { "apikey", "authorization", "cookie", "credential", "credentials", "passphrase", "passwd", "password", "secret", "token" },
            S.SensitiveKeySegments.OrderBy(k => k, StringComparer.Ordinal));
        Assert.Equal(new[] { ("api", "key"), ("private", "key"), ("access", "key") }, S.SensitiveKeyPairs);
        Assert.Equal(
            new[] { "count", "enabled", "expires", "expiry", "hash", "kind", "len", "length", "required", "size", "ttl", "type" },
            S.NonSecretKeySuffixes.OrderBy(k => k, StringComparer.Ordinal));
    }

    [Fact]
    public void Redacts_Strings_And_Keeps_Scalars()
    {
        var input = new Dictionary<string, object?>
        {
            ["a"] = new object?[] { "S3cret1", new Dictionary<string, object?> { ["b"] = "x S3cret2" }, 1.5, true, null },
            ["bytes"] = new byte[] { 1, 2 },
            ["imap"] = new Dictionary<int, string> { [7] = "S3cretD" },
        };
        var got = JsonSerializer.Serialize(S.Redact(input, Secret));
        Assert.Equal("{\"a\":[\"[REDACTED]\",{\"b\":\"x [REDACTED]\"},1.5,true,null],\"bytes\":\"AQI=\",\"imap\":{\"7\":\"[REDACTED]\"}}", got);
        Assert.Equal("S3cret1", ((object?[])input["a"]!)[0]);
        Assert.Equal(7, S.Redact(7, Secret));
        Assert.Null(S.Redact(null, Secret));
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void Depth_Cap_Boundary(bool map)
    {
        Assert.Equal("[REDACTED]", Innermost(S.Redact(Nest(S.RedactMaxDepth, "S3cretLeaf", map), Secret)));
        var past = S.Redact(Nest(S.RedactMaxDepth + 1, "S3cretLeaf", map), Secret);
        Assert.Equal(S.DepthLimitMarker, Innermost(past));
        Assert.DoesNotContain("S3cretLeaf", JsonSerializer.Serialize(past));
        Assert.Equal(5, Innermost(S.Redact(Nest(S.RedactMaxDepth, 5, map), Secret)));
    }

    [Fact]
    public void MaxDepth_Override()
    {
        var got = S.Redact(new Dictionary<string, object?> { ["a"] = new Dictionary<string, object?> { ["b"] = "x" } }, Secret, maxDepth: 1);
        Assert.Equal("{\"a\":\"[NESTED_REDACTED]\"}", JsonSerializer.Serialize(got));
        Assert.Equal(S.DepthLimitMarker, S.Redact(new List<object?> { "x" }, Secret, maxDepth: 0));
    }

