using System.Text.Json;
using Provide.Uterm.Vt;
using VtScreen = Provide.Uterm.Vt.Screen;

namespace Provide.Uterm.Tests.VtSuite;

/// <summary>
/// The vt golden corpus (vt_golden.json, generated from pyte by
/// packages/provide-uterm-ts/testdata/gen_vt_golden.py; the copy under testdata
/// is kept identical by <see cref="SharedCorpusParityTests"/>) replayed through
/// this port's screen. Every record is the state pyte leaves for its stream:
/// the display, the cursor and every cell's text and attributes. The cases run
/// with UTF-8 mode on, the DEC graphics cases with it off, as the reference's
/// UTF-8 sessions run, and the records once kept as divergences hold pyte's
/// state, which this port reproduces. The reference-fix records are recorded
/// through the Python emulator's own screen, for the streams plain pyte raises
/// on. The corpus also exports the reference's wcwidth and combining tables,
/// which this port's are held to code point by code point: they are generated by
/// scripts/gen_unicode_tables.py, which a mismatch means needs rerunning.
/// </summary>
public class VtGoldenCorpusTests
{
    private static readonly JsonElement Corpus =
        JsonDocument.Parse(File.ReadAllText(TestData.PathTo("vt_golden.json"))).RootElement;

    public static TheoryData<string, int> Records()
    {
        var data = new TheoryData<string, int>();
        foreach (var section in new[] { "cases", "dec_graphics_cases", "stall_divergences", "reference_fix_cases" })
        {
            var count = Corpus.GetProperty(section).GetArrayLength();
            for (var i = 0; i < count; i++)
            {
                data.Add(section, i);
            }
        }

        return data;
    }

    [Theory]
    [MemberData(nameof(Records))]
    public void MatchesPyte(string section, int index)
    {
        var record = Corpus.GetProperty(section)[index];
        // The divergence records are 20x6 and keep their state under "pyte".
        var cols = record.TryGetProperty("cols", out var c) ? c.GetInt32() : 20;
        var rows = record.TryGetProperty("rows", out var r) ? r.GetInt32() : 6;
        var state = record.TryGetProperty("state", out var s) ? s : record.GetProperty("pyte");
        var screen = new VtScreen(cols, rows);
        var stream = new VtStream(screen) { UseUtf8 = section != "dec_graphics_cases" };
        foreach (var chunk in record.GetProperty("chunks").EnumerateArray())
        {
            stream.Feed(chunk.GetString()!);
        }

        var name = record.GetProperty("name").GetString();
        Assert.True(
            state.GetProperty("display").EnumerateArray().Select(line => line.GetString()).SequenceEqual(screen.Display()),
            $"{name}: display");
        var cursor = state.GetProperty("cursor");
        Assert.Equal(
            (cursor.GetProperty("x").GetInt32(), cursor.GetProperty("y").GetInt32(), cursor.GetProperty("hidden").GetBoolean()),
            (screen.Cursor.X, screen.Cursor.Y, screen.Cursor.Hidden));
        var expected = new Dictionary<(int, int), JsonElement>();
        foreach (var cell in state.GetProperty("cells").EnumerateArray())
        {
            expected[(cell.GetProperty("y").GetInt32(), cell.GetProperty("x").GetInt32())] = cell;
        }

        for (var y = 0; y < rows; y++)
        {
            for (var x = 0; x < cols; x++)
            {
                var actual = screen.At(y, x);
                var want = expected.TryGetValue((y, x), out var cell)
                    ? (cell.GetProperty("data").GetString(), cell.GetProperty("fg").GetString(), cell.GetProperty("bg").GetString(),
                        cell.GetProperty("bold").GetBoolean(), cell.GetProperty("italics").GetBoolean(),
                        cell.GetProperty("underscore").GetBoolean(), cell.GetProperty("reverse").GetBoolean(),
                        cell.GetProperty("strikethrough").GetBoolean(), cell.GetProperty("blink").GetBoolean())
                    : (" ", "default", "default", false, false, false, false, false, false);
                Assert.Equal(
                    want,
                    (actual.Data, actual.FG, actual.BG, actual.Bold, actual.Italics, actual.Underscore, actual.Reverse,
                        actual.Strikethrough, actual.Blink));
            }
        }
    }

    [Fact]
    public void WidthTablesMatchTheReference()
    {
        var widths = new Dictionary<int, int>();
        foreach (var range in Corpus.GetProperty("wcwidth_ranges").EnumerateArray())
        {
            for (var point = range[0].GetInt32(); point <= range[1].GetInt32(); point++)
            {
                widths[point] = range[2].GetInt32();
            }
        }

        var combining = new Dictionary<int, int>();
        foreach (var range in Corpus.GetProperty("combining_classes").EnumerateArray())
        {
            for (var point = range[0].GetInt32(); point <= range[1].GetInt32(); point++)
            {
                combining[point] = range[2].GetInt32();
            }
        }

        for (var point = 0; point <= 0x10FFFF; point++)
        {
            var want = widths.TryGetValue(point, out var width) ? width : 1;
            Assert.True(Wcwidth.RuneWidth(point) == want, $"RuneWidth(0x{point:X}) = {Wcwidth.RuneWidth(point)}, want {want}");
            var cc = combining.TryGetValue(point, out var value) ? value : 0;
            Assert.True(Wcwidth.CombiningClass(point) == cc, $"CombiningClass(0x{point:X}) = {Wcwidth.CombiningClass(point)}, want {cc}");
        }
    }

    [Fact]
    public void NormalizationTablesMatchTheReference()
    {
        var decompositions = Corpus.GetProperty("canonical_decompositions").EnumerateArray().ToArray();
        var compositions = Corpus.GetProperty("composition_pairs").EnumerateArray().ToArray();
        Assert.Equal(decompositions.Length, UnicodeNormTables.CanonicalDecomp.Count);
        Assert.Equal(compositions.Length, UnicodeNormTables.CompositionPairs.Count);
        foreach (var d in decompositions)
        {
            Assert.Equal((d[1].GetInt32(), d[2].GetInt32()), UnicodeNormTables.CanonicalDecomp[d[0].GetInt32()]);
        }

        foreach (var c in compositions)
        {
            Assert.Equal(c[2].GetInt32(), UnicodeNormTables.CompositionPairs[(c[0].GetInt32(), c[1].GetInt32())]);
        }
    }
}
