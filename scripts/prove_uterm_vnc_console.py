"""Prove first-party uterm VNC console path: lab + server + binary /gui/vnc.

Live path (not mocked):
  1. Ensure ``uterm-test-vnc`` lab image/container (plain :5900, TLS :5901)
  2. Start ``uterm server`` with lab ``[[graphical_targets]]``
  3. Wait for auto-started shell worker; REST acquire as operator
  4. Open binary WebSocket to ``/worker/…/hijack/…/gui/vnc?target_id=…``
  5. Complete RFB ProtocolVersion exchange **through the relay**
  6. Repeat plain path twice; once for TLS; once denied path
  7. Optionally open the baked ``vnc.html`` page and screenshot

Usage (repo root)::

    uv run python scripts/prove_uterm_vnc_console.py
    uv run python scripts/prove_uterm_vnc_console.py --evidence-dir /path --runs 2
    SCRATCH=/path uv run python scripts/prove_uterm_vnc_console.py

Exit 0 only when every required observation succeeds.
"""

