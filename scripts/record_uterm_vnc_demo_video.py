def start_lab_with_demo_url(
    *,
    name: str,
    demo_url: str,
    host_plain: int = LAB_HOST_PLAIN,
    host_tls: int = LAB_HOST_TLS,
) -> tuple[int, int]:
    """Start lab container; Chromium opens *demo_url* (host uterm text console)."""
    vnc_lab._remove_container(name)
    result = subprocess.run(
        [
            "docker",
            "run",
            "-d",
            "--name",
            name,
            "--shm-size",
            vnc_lab.DEFAULT_SHM,
            "--add-host=host.docker.internal:host-gateway",
            "-p",
            f"{host_plain}:{vnc_lab.RFB_PLAIN_PORT}",
            "-p",
            f"{host_tls}:{vnc_lab.RFB_SSL_PORT}",
            "-e",
            f"DEMO_URL={demo_url}",
            vnc_lab.IMAGE_NAME,
        ],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"docker run failed: {result.stderr.strip()[:500]}")
    return host_plain, host_tls


def lab_chrome_args(name: str) -> str:
    """Return lab Chromium command lines (for verifying DEMO_URL stuck)."""
    result = subprocess.run(
        ["docker", "exec", name, "bash", "-lc", "ps -C chromium -o args= 2>/dev/null | tr '\\n' '|'"],
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )
    return (result.stdout or "").strip()


def http_json(method: str, url: str, *, headers: dict[str, str], body: dict | None = None) -> tuple[int, object]:
    data = None if body is None else json.dumps(body).encode("utf-8")
    req = urllib.request.Request(url, data=data, headers=headers, method=method)  # noqa: S310
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:  # noqa: S310
            raw = resp.read().decode("utf-8")
            return resp.status, json.loads(raw) if raw else {}
    except urllib.error.HTTPError as exc:
        raw = exc.read().decode("utf-8", errors="replace")
        try:
            parsed: object = json.loads(raw) if raw else {}
        except json.JSONDecodeError:
            parsed = raw
        return exc.code, parsed


def acquire_shell(base: str, headers: dict[str, str], *, session: str = SHELL_SESSION) -> tuple[str | None, list[str]]:
    """Acquire a REST hijack lease on the reference shell session."""
    log: list[str] = []
    status, payload = http_json(
        "POST",
        f"{base}/worker/{session}/hijack/acquire",
        headers=headers,
        body={"owner": "demo-driver", "lease_s": 300},
    )
    if status != 200 or not isinstance(payload, dict):
        log.append(f"acquire_{session}=status_{status} body={payload!r}")
        return None, log
    hid = str(payload["hijack_id"])
    log.append(f"acquire_{session}={hid}")
    return hid, log


def send_shell_keys(
    base: str,
    headers: dict[str, str],
    hid: str,
    keys: str,
    *,
    session: str = SHELL_SESSION,
) -> tuple[int, object]:
    return http_json(
        "POST",
        f"{base}/worker/{session}/hijack/{hid}/send",
        headers=headers,
        body={"keys": keys, "timeout_ms": 1500},
    )


def seed_shell_banner(base: str, headers: dict[str, str], hid: str) -> list[str]:
    """Minimal seed so nested browser has *something* on first paint."""
    log: list[str] = []
    for cmd in (
        "/clear\r",
        "/nick demo\r",
        "/say provide-uterm · nested browser demo starting…\r",
        "/say (live stream will paint below)\r",
    ):
        st, body = send_shell_keys(base, headers, hid, cmd)
        if st >= 400:
            log.append(f"seed_err={st} {body!r}")
        time.sleep(0.08)
    log.append("seed_ok")
    return log


