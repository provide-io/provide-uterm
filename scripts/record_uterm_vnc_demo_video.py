"""Record video: first-party uterm VNC console showing lab browser on text demos.

End-to-end proof (not mocked)::

  1. Start uterm server (shell demo session + RFB graphical targets)
  2. Start uterm-test-vnc lab with Chromium pointed at the host's
     ``/_terminal/terminal.html`` text console (and a second tab/window path)
  3. Drive live shell output (text-based demos) into the session
  4. Open host Playwright on first-party ``vnc.html`` and record webm + stills

Usage (repo root)::

    uv run python scripts/record_uterm_vnc_demo_video.py
    uv run python scripts/record_uterm_vnc_demo_video.py --seconds 18 --skip-build
"""

